"""Writes app/src/main/java/io/embodit/foldguide/domain/fold/FoldLibraryData.kt from models.py.

    python -I tools/foldlib/gen_kotlin.py

Fails (exit 1) when any variant does not pass models.check (landings, bounds, copy budgets).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import models as M  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "app", "src", "main", "java", "io", "embodit", "foldguide", "domain", "fold", "FoldLibraryData.kt")

KIND = {"fold": "FOLD", "crease": "CREASE", "flip": "FLIP", "draw": "DRAW", "form": "FORM", "cut": "CUT", "rotate": "ROTATE"}
CAT = {"basics": "BASICS", "animals": "ANIMALS", "flowers": "FLOWERS", "everyday": "EVERYDAY", "boxes": "BOXES", "planes": "PLANES"}
POSE = {"square": "SQUARE", "diamond": "DIAMOND", "rect": "RECT"}


def f(x):
    x = round(float(x), 2)
    if x == 0:
        x = 0.0
    s = ("%.2f" % x).rstrip("0").rstrip(".")
    if "." not in s:
        s += ".0"
    return s + "f"


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def pt(p):
    return "p(%s, %s)" % (f(p[0]), f(p[1]))


def line(l):
    return "%s(%s, %s, %s, %s)" % ("m" if l[2] else "v", f(l[0][0]), f(l[0][1]), f(l[1][0]), f(l[1][1]))


def landing(l):
    if l[0] == "at":
        return "at(%s, %s)" % (f(l[1][0]), f(l[1][1]))
    return "seg(%s, %s, %s, %s)" % (f(l[1][0]), f(l[1][1]), f(l[2][0]), f(l[2][1]))


def step(st, reset=None):
    args = ["StepKind.%s" % KIND[st.kind], q(st.zh), q(st.en)]
    if st.lines:
        args.append("listOf(%s)" % ", ".join(line(l) for l in st.lines))
        args.append("listOf(%s)" % ", ".join(pt(p) for p in st.picks))
    if st.top:
        args.append("topOnly = true")
    if st.landings:
        args.append("landings = listOf(%s)" % ", ".join(landing(l) for l in st.landings))
    if st.dots:
        args.append("dots = listOf(%s)" % ", ".join(pt(p) for p in st.dots))
    if st.form:
        args.append("form = FormKind.%s" % st.form)
    if st.legend:
        args.append("legend = %s" % q(st.legend))
    if st.ranges:
        args.append("layers = listOf(%s)" % ", ".join("%d..%d" % (a, b) for a, b in st.ranges))
    if reset:
        args.append("resetTo = StartPose.%s" % reset)
    if getattr(st, "leaves_crease", False):
        args.append("leavesCrease = true")
    return "Step(%s)" % ", ".join(args)


def steps_fn(name, steps, resets=None):
    resets = resets or {}
    body = ",\n".join("            " + step(s, resets.get(i)) for i, s in enumerate(steps))
    return "    private fun %s(): List<Step> =\n        listOf(\n%s,\n        )\n" % (name, body)


def camel(s):
    c = "".join(w.capitalize() for w in s.replace("@", "_").split("_"))
    return c[0].lower() + c[1:]


def main():
    bad = []
    fns = M.library()
    square, rect, prep = [], [], {}
    entries = []
    for fn in fns:
        for paper in M.PAPERS:
            if not M.available(fn, paper):
                continue
            v = M.variant(fn, paper)
            p = M.check(v)
            if p:
                bad.append((v["key"], p))
            if v["needs"] == "square" and paper == "square":
                square.append(v)
            elif v["needs"] == "rect":
                rect.append(v)
            else:
                key = (paper, v["pose"] == "diamond")
                if key not in prep:
                    prep[key] = (v["steps"][: v["prep"]], v["resetNames"])
        first = M.variant(fn, "square" if M.available(fn, "square") else M.RECT_PAPERS[0])
        entries.append(first)
    if bad:
        for k, p in bad:
            print(k, p)
        sys.exit(1)

    out = []
    out.append("package io.embodit.foldguide.domain.fold\n")
    out.append("// GENERATED by tools/foldlib/gen_kotlin.py from tools/foldlib/models.py + library_v011.py. Do not edit by hand:")
    out.append("// change the Python model, run `python -I tools/foldlib/models.py` (checks) and the generator, then the unit tests.\n")
    out.append("@Suppress(\"LargeClass\", \"MaxLineLength\")")
    out.append("internal object FoldLibraryData {")
    out.append("    private fun p(x: Float, y: Float) = Pt(x, y)\n")
    out.append("    private fun v(x0: Float, y0: Float, x1: Float, y1: Float) = FoldLine(Pt(x0, y0), Pt(x1, y1), mountain = false)\n")
    out.append("    private fun m(x0: Float, y0: Float, x1: Float, y1: Float) = FoldLine(Pt(x0, y0), Pt(x1, y1), mountain = true)\n")
    out.append("    private fun at(x: Float, y: Float): Landing = Landing.At(Pt(x, y))\n")
    out.append("    private fun seg(x0: Float, y0: Float, x1: Float, y1: Float): Landing = Landing.Seg(Pt(x0, y0), Pt(x1, y1))\n")
    out.append("    /** The library in display order: id, names, category, paper, start pose, minutes, level, result. */")
    out.append("    val entries: List<FoldEntry> =")
    out.append("        listOf(")
    for e in entries:
        out.append("            FoldEntry(%s, %s, %s, Category.%s, needsRect = %s, pose = StartPose.%s, minutes = %d, level = %d, resultZh = %s, resultEn = %s)," % (
            q(e["id"]), q(e["nameZh"]), q(e["nameEn"]), CAT[e["cat"]], "true" if e["needs"] == "rect" else "false", POSE[e["pose"]], e["minutes"], e["level"], q(e["resultZh"]), q(e["resultEn"])))
    out.append("        )\n")
    out.append("    /** Steps of a square model on the 15 cm square. */")
    out.append("    fun squareSteps(id: String): List<Step>? =")
    out.append("        when (id) {")
    for v in square:
        out.append("            %s -> %s()" % (q(v["id"]), camel("sq_" + v["id"])))
        pass
    out.append("            else -> null")
    out.append("        }\n")
    out.append("    /** Steps of a printer-paper model (authored on the paper's own proportions). */")
    out.append("    fun rectSteps(id: String, paper: Paper): List<Step>? =")
    out.append("        when (id + \"@\" + paper.id) {")
    for v in rect:
        out.append("            %s -> %s()" % (q(v["key"]), camel("rect_" + v["key"])))
    out.append("            else -> null")
    out.append("        }\n")
    out.append("    /** Printer paper -> square: fold a corner over, crease and cut the strip, unfold (then turn it for a diamond start). */")
    out.append("    fun prepSteps(paper: Paper, diamond: Boolean): List<Step> =")
    out.append("        when {")
    for (paper, diamond) in sorted(prep):
        out.append("            paper == Paper.%s && %sdiamond -> %s()" % (paper.upper(), "" if diamond else "!", camel("prep_%s_%s" % (paper, "diamond" if diamond else "square"))))
    out.append("            else -> emptyList()")
    out.append("        }\n")
    for v in square:
        out.append(steps_fn(camel("sq_" + v["id"]), v["steps"]))
    for v in rect:
        out.append(steps_fn(camel("rect_" + v["key"]), v["steps"], v["resetNames"]))
    for (paper, diamond) in sorted(prep):
        st, resets = prep[(paper, diamond)]
        out.append(steps_fn(camel("prep_%s_%s" % (paper, "diamond" if diamond else "square")), st, resets))
    out.append("}")
    text = "\n".join(out) + "\n"
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("wrote %s: %d entries, %d square, %d rect, %d prep" % (OUT, len(entries), len(square), len(rect), len(prep)))


if __name__ == "__main__":
    main()
